/**
 * Script to fetch the latest model context window data from LiteLLM
 * and update the built-in mapping table in data/model-context.json.
 *
 * Usage: pnpm run update-model-context
 */

const https = require('https');
const fs = require('fs');
const path = require('path');

const LITELLM_JSON_URL =
  'https://raw.githubusercontent.com/BerriAI/litellm/main/model_prices_and_context_window.json';
const OUTPUT_FILE = path.join(__dirname, '..', 'data', 'model-context.json');

function fetchJson(url) {
  return new Promise((resolve, reject) => {
    https
      .get(url, (res) => {
        if (res.statusCode !== 200) {
          reject(new Error(`HTTP ${res.statusCode}: ${res.statusMessage}`));
          return;
        }
        let data = '';
        res.on('data', (chunk) => (data += chunk));
        res.on('end', () => {
          try {
            resolve(JSON.parse(data));
          } catch (e) {
            reject(new Error('Failed to parse JSON response'));
          }
        });
      })
      .on('error', reject);
  });
}

function extractChatModels(data) {
  const result = {};
  for (const [modelName, config] of Object.entries(data)) {
    if (typeof config !== 'object' || config === null) {
      continue;
    }
    if (config.mode !== 'chat') {
      continue;
    }

    const maxInputTokens = config.max_input_tokens;
    if (typeof maxInputTokens === 'number' && maxInputTokens > 0) {
      result[modelName] = maxInputTokens;
    }
  }
  return result;
}

async function main() {
  console.log('Fetching LiteLLM model data...');
  const data = await fetchJson(LITELLM_JSON_URL);

  console.log('Extracting chat models with context windows...');
  const chatModels = extractChatModels(data);
  const count = Object.keys(chatModels).length;

  console.log(`Found ${count} chat models with context window info.`);

  const output = {
    _comment: 'Auto-generated by scripts/update-model-context.js',
    _updated: new Date().toISOString(),
    _source: LITELLM_JSON_URL,
    models: chatModels
  };

  fs.writeFileSync(OUTPUT_FILE, JSON.stringify(output, null, 2) + '\n', 'utf-8');
  console.log(`Updated ${OUTPUT_FILE}`);
}

main().catch((err) => {
  console.error('Failed:', err.message);
  process.exit(1);
});
