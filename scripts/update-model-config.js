/**
 * Script to fetch the latest model context window data from LiteLLM and OpenRouter
 * and update the built-in mapping table in data/model-config.json.
 *
 * Usage: pnpm run update-model-context
 */

const https = require('https');
const fs = require('fs');
const path = require('path');

const LITELLM_JSON_URL =
  'https://raw.githubusercontent.com/BerriAI/litellm/main/model_prices_and_context_window.json';
const OPENROUTER_JSON_URL = 'https://openrouter.ai/api/v1/models?output_modalities=text';

const OUTPUT_FILE = path.join(__dirname, '..', 'data', 'model-config.json');

function fetchJson(url) {
  return new Promise((resolve, reject) => {
    https
      .get(url, (res) => {
        if (res.statusCode !== 200) {
          reject(new Error(`HTTP ${res.statusCode}: ${res.statusMessage}`));
          return;
        }
        let data = '';
        res.on('data', (chunk) => (data += chunk));
        res.on('end', () => {
          try {
            resolve(JSON.parse(data));
          } catch (e) {
            reject(new Error('Failed to parse JSON response'));
          }
        });
      })
      .on('error', reject);
  });
}

function processLiteLLMModels(data) {
  const result = {};
  for (const [modelName, config] of Object.entries(data)) {
    if (typeof config !== 'object' || config === null) {
      continue;
    }
    if (config.mode !== 'chat') {
      continue;
    }

    const max_tokens = config.max_tokens || config.max_output_tokens;
    const max_input_token = config.max_input_tokens;

    if (max_tokens || max_input_token) {
      result[modelName] = {
        max_tokens: typeof max_tokens === 'number' ? max_tokens : undefined,
        max_input_token: typeof max_input_token === 'number' ? max_input_token : undefined
      };
    }
  }
  return result;
}

function processOpenRouterModels(data) {
  const result = {};
  if (!data || !Array.isArray(data.data)) {
    return result;
  }

  for (const model of data.data) {
    const modelName = model.id;
    const max_tokens = model.max_completion_tokens;
    const max_input_token = model.context_length;

    if (max_tokens || max_input_token) {
      result[modelName] = {
        max_tokens: typeof max_tokens === 'number' ? max_tokens : undefined,
        max_input_token: typeof max_input_token === 'number' ? max_input_token : undefined
      };
    }
  }
  return result;
}

async function main() {
  console.log('Fetching LiteLLM model data...');
  const liteData = await fetchJson(LITELLM_JSON_URL).catch((err) => {
    console.error('LiteLLM fetch failed:', err.message);
    return {};
  });

  console.log('Fetching OpenRouter model data...');
  const orData = await fetchJson(OPENROUTER_JSON_URL).catch((err) => {
    console.error('OpenRouter fetch failed:', err.message);
    return { data: [] };
  });

  console.log('Processing models...');
  const liteModels = processLiteLLMModels(liteData);
  const orModels = processOpenRouterModels(orData);

  // Merge results, OpenRouter takes precedence if overlap
  const mergedModels = { ...liteModels, ...orModels };
  const count = Object.keys(mergedModels).length;

  console.log(`Found total ${count} models.`);

  const output = {
    _comment: 'Auto-generated by scripts/update-model-context.js',
    _updated: new Date().toISOString(),
    _sources: [LITELLM_JSON_URL, OPENROUTER_JSON_URL],
    models: mergedModels
  };

  const dir = path.dirname(OUTPUT_FILE);
  if (!fs.existsSync(dir)) {
    fs.mkdirSync(dir, { recursive: true });
  }
  fs.writeFileSync(OUTPUT_FILE, JSON.stringify(output, null, 2) + '\n', 'utf-8');
  console.log(`Updated ${OUTPUT_FILE}`);
}

main().catch((err) => {
  console.error('Failed:', err.message);
  process.exit(1);
});
